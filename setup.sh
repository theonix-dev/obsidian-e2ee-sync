#!/usr/bin/env bash
#
# setup.sh — interactive setup wizard for Obsidian E2EE Sync.
#
# Runs on Linux, macOS, WSL and Git-Bash (bash 3.2+). It can:
#   1) configure and run the sync server   (server/server.js — zero npm deps)
#   2) build the plugin and install it into one of your vaults
#   3) both of the above (default)
#   4) stop a previously background-started server
#
# Usage:  ./setup.sh            (interactive — every parameter is asked)
#         ./setup.sh --help
#
# The shared configuration file server/run.env (KEY=VALUE, chmod 600) is
# compatible with setup.ps1 — configure once with either script, reuse anywhere.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SERVER_DIR="$SCRIPT_DIR/server"
PLUGIN_DIR="$SCRIPT_DIR/plugin"
PLUGIN_ID="e2ee-vault-sync"
RUN_ENV="$SERVER_DIR/run.env"
PID_FILE="$SERVER_DIR/server.pid"
LOG_FILE="$SERVER_DIR/server.log"
BOM=$'\xEF\xBB\xBF'

[ -d "$SERVER_DIR" ] || { echo "server/ folder not found next to this script." >&2; exit 1; }
[ -d "$PLUGIN_DIR" ] || { echo "plugin/ folder not found next to this script." >&2; exit 1; }

# ---------------------------------------------------------------- ui helpers
if [ -t 0 ] && [ -t 1 ]; then
  C_G=$'\033[32m'; C_Y=$'\033[33m'; C_R=$'\033[31m'; C_B=$'\033[1m'; C_D=$'\033[2m'; C_0=$'\033[0m'
else
  C_G=''; C_Y=''; C_R=''; C_B=''; C_D=''; C_0=''
fi
say()  { printf '%s\n' "${C_B}==>${C_0} $*"; }
ok()   { printf '%s\n' " ${C_G}[ok]${C_0} $*"; }
warn() { printf '%s\n' " ${C_Y}[!]${C_0}  $*" >&2; }
die()  { printf '%s\n' " ${C_R}[x]${C_0}  $*" >&2; exit 1; }

prompt() {  # prompt QUESTION DEFAULT -> result in $REPLY (empty answer = default)
  local q="$1" def="$2" ans
  if [ -n "$def" ]; then
    printf '%s' "${C_B}${q}${C_0} ${C_D}[${def}]${C_0}: "
  else
    printf '%s' "${C_B}${q}${C_0}: "
  fi
  if ! read -r ans; then
    printf '\n'
    die "Input closed (stdin EOF) — run without piping for interactive use."
  fi
  REPLY="${ans:-$def}"
}

confirm() {  # confirm QUESTION [default y|n]
  local def="${2:-y}" ans
  while :; do
    prompt "$1 [y/n]" "$def"
    ans="$(printf '%s' "$REPLY" | tr '[:upper:]' '[:lower:]')"
    case "$ans" in
      y|yes) return 0 ;;
      n|no)  return 1 ;;
      *)     warn "Please answer y or n." ;;
    esac
  done
}

# ---------------------------------------------------------------- checks/utils
gen_token() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 32
  else
    od -An -N32 -tx1 /dev/urandom | tr -d ' \n'
  fi
}

assert_node() {
  command -v node >/dev/null 2>&1 \
    || die "'node' not found. Install Node.js >= 18 from https://nodejs.org"
  local v
  v="$(node -v 2>/dev/null | sed 's/^v//; s/\..*$//')"
  case "$v" in ''|*[!0-9]*) die "Cannot parse node version ($(node -v 2>/dev/null))." ;; esac
  [ "$v" -ge 18 ] || die "Node.js >= 18 required (found $(node -v))."
}

port_busy() { (exec 3<>"/dev/tcp/$1/$2") >/dev/null 2>&1; }

health_check() {  # health_check HOST PORT -> 0 if server answers
  node -e "fetch('http://'+process.argv[1]+':'+process.argv[2]+'/api/health').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))" "$1" "$2" >/dev/null 2>&1
}

lan_ip() {
  local ip
  ip="$(hostname -I 2>/dev/null | cut -d' ' -f1)"
  [ -n "$ip" ] || ip="$(ipconfig getifaddr en0 2>/dev/null)"
  printf '%s' "$ip"
}

print_token_masked() {  # first 8 chars + "…" + last 4
  local t="$1"
  if [ "${#t}" -gt 16 ]; then
    printf '%s…%s' "${t%"${t#????????}"}" "${t#"${t%????}"}"
  else
    printf '%s' "$t"
  fi
}

usage() {
  cat <<'EOF'
Usage: ./setup.sh

Interactive wizard that (1) configures and runs the sync server and
(2) installs the Obsidian plugin into a vault of your choice.
Every question shows a default in [brackets] — press Enter to accept it.
EOF
}

# ---------------------------------------------------------------- server flow
write_run_env() {
  local old_umask
  old_umask="$(umask)"
  umask 177
  {
    echo '# Generated by setup.sh / setup.ps1 — loaded on server start.'
    echo '# Keep AUTH_TOKEN secret (file permissions: 600).'
    printf 'PORT=%s\n' "$PORT"
    printf 'HOST=%s\n' "$HOST_BIND"
    printf 'DATA_DIR="%s"\n' "$DATA_DIR"
    printf 'AUTH_TOKEN=%s\n' "$TOKEN"
  } > "$RUN_ENV"
  chmod 600 "$RUN_ENV"
  umask "$old_umask"
}

load_run_env() {  # exports PORT/HOST_BIND/DATA_DIR/TOKEN (+AUTH_TOKEN); strips a UTF-8 BOM if present
  set -a
  # shellcheck disable=SC1090
  . <(sed "1s/^$BOM//" "$RUN_ENV")
  set +a
  HOST_BIND="${HOST:-127.0.0.1}"
  TOKEN="${AUTH_TOKEN:-}"
}

ask_server_params() {
  # --- port
  while :; do
    prompt "Port to listen on" "${PORT:-8080}"
    case "$REPLY" in ''|*[!0-9]*) warn "Port must be a number."; continue ;; esac
    if [ "$REPLY" -lt 1 ] || [ "$REPLY" -gt 65535 ]; then warn "Port must be 1–65535."; continue; fi
    if port_busy "${HOST_BIND:-127.0.0.1}" "$REPLY"; then warn "Port $REPLY is already in use."; continue; fi
    PORT="$REPLY"; break
  done

  # --- bind host
  prompt "Bind address" "${HOST_BIND:-127.0.0.1}"
  HOST_BIND="$REPLY"
  if [ "$HOST_BIND" = "0.0.0.0" ] || [ "$HOST_BIND" = "::" ]; then
    warn "Binding to all interfaces: anything that reaches this machine can connect."
    warn "For internet exposure put nginx + HTTPS in front (see server/nginx.conf.example)."
  fi

  # --- data dir
  prompt "Data directory" "${DATA_DIR:-$SERVER_DIR/data}"
  DATA_DIR="${REPLY/#\~/$HOME}"
  mkdir -p "$DATA_DIR"

  # --- token
  prompt "API token — press Enter to generate a secure one, or paste your own" ""
  if [ -n "$REPLY" ]; then
    [ "${#REPLY}" -ge 16 ] || die "Token must be at least 16 characters."
    TOKEN="$REPLY"
  else
    TOKEN="$(gen_token)"
    [ -n "$TOKEN" ] || die "Failed to generate a token (no openssl, no /dev/urandom?)."
  fi
}

server_flow() {
  assert_node

  if [ -f "$RUN_ENV" ]; then
    load_run_env
    if [ -n "${PORT:-}" ] && [ -n "${HOST_BIND:-}" ] && [ -n "${DATA_DIR:-}" ] && [ -n "${TOKEN:-}" ]; then
      say "Found saved configuration: $RUN_ENV"
      printf '      port=%s  host=%s  data=%s\n' "$PORT" "$HOST_BIND" "$DATA_DIR"
      printf '      token=%s\n' "$(print_token_masked "$TOKEN")"
      if confirm "Change these settings" "n"; then
        ask_server_params
        write_run_env
      else
        write_run_env   # normalize back to canonical form (values unchanged)
      fi
    else
      warn "Saved configuration in $RUN_ENV is incomplete — reconfiguring."
      ask_server_params
      write_run_env
    fi
  else
    ask_server_params
    write_run_env
  fi

  echo
  say "Configuration summary"
  printf '      Server URL : http://127.0.0.1:%s  (for this machine)\n' "$PORT"
  local ip; ip="$(lan_ip)"
  [ -n "$ip" ] && printf '      LAN URL    : http://%s:%s  (same Wi-Fi; enable in plugin)\n' "$ip" "$PORT" || true
  printf '      Data dir   : %s\n' "$DATA_DIR"
  printf '      API token  : %s   (full value in %s)\n' "$(print_token_masked "$TOKEN")" "$RUN_ENV"
  echo

  prompt "Start mode — (f)oreground, Ctrl+C stops, or (b)ackground" "b"
  case "$REPLY" in
    f*|F*) MODE=foreground ;;
    *)     MODE=background ;;
  esac

  if [ "$MODE" = "foreground" ]; then
    say "Starting in FOREGROUND — press Ctrl+C to stop."
    exec env PORT="$PORT" HOST="$HOST_BIND" DATA_DIR="$DATA_DIR" AUTH_TOKEN="$TOKEN" \
      node "$SERVER_DIR/server.js"
  fi

  say "Starting in BACKGROUND (log: $LOG_FILE)."
  nohup env PORT="$PORT" HOST="$HOST_BIND" DATA_DIR="$DATA_DIR" AUTH_TOKEN="$TOKEN" \
    node "$SERVER_DIR/server.js" >>"$LOG_FILE" 2>&1 &
  local pid=$!
  echo "$pid" > "$PID_FILE"
  sleep 1

  local check_host="$HOST_BIND"
  if [ "$check_host" = "0.0.0.0" ] || [ "$check_host" = "::" ]; then
    check_host="127.0.0.1"
  fi
  if health_check "$check_host" "$PORT"; then
    ok "Server is running (pid $pid) — http://$check_host:$PORT"
  else
    kill "$pid" 2>/dev/null || true
    rm -f "$PID_FILE"
    echo "----- last log lines ($LOG_FILE) -----" >&2
    tail -n 20 "$LOG_FILE" >&2 || true
    die "Server failed to start — see the log above."
  fi

  echo
  say "To stop it later:  ./setup.sh  ->  choose 4"
}

stop_flow() {
  if [ ! -f "$PID_FILE" ]; then
    die "No PID file ($PID_FILE) — the server was not started in background by this script."
  fi
  local pid; pid="$(cat "$PID_FILE")"
  if kill -0 "$pid" 2>/dev/null; then
    kill "$pid"
    ok "Server stopped (pid $pid)."
  else
    ok "Process $pid was already stopped."
  fi
  rm -f "$PID_FILE"
}

# ---------------------------------------------------------------- plugin flow
plugin_flow() {
  assert_node

  local build="n"
  if [ ! -f "$PLUGIN_DIR/main.js" ]; then
    build="y"
  elif confirm "Plugin is already built — rebuild from source (needs npm)" "y"; then
    build="y"
  fi

  if [ "$build" = "y" ]; then
    command -v npm >/dev/null 2>&1 \
      || die "'npm' not found. Install Node.js (includes npm) or copy main.js from another machine."
    say "Building plugin…"
    if [ ! -d "$PLUGIN_DIR/node_modules" ]; then
      (cd "$PLUGIN_DIR" && npm install --no-fund --no-audit) || die "npm install failed."
    fi
    (cd "$PLUGIN_DIR" && npm run build) || die "Plugin build failed."
  fi

  [ -f "$PLUGIN_DIR/main.js" ] || die "$PLUGIN_DIR/main.js is missing — build it first."

  local vault
  while :; do
    prompt "Path to your Obsidian vault (the folder that contains .obsidian)" ""
    vault="${REPLY/#\~/$HOME}"
    if [ -z "$vault" ]; then warn "Path cannot be empty."; continue; fi
    if [ ! -d "$vault" ]; then warn "Not a directory: $vault"; continue; fi
    if [ -d "$vault/.obsidian" ]; then break; fi
    warn "No .obsidian folder inside — this does not look like an opened Obsidian vault."
    if confirm "Use this folder anyway" "n"; then break; fi
  done

  local dest="$vault/.obsidian/plugins/$PLUGIN_ID"
  mkdir -p "$dest"
  local f
  for f in main.js manifest.json styles.css; do
    [ -f "$PLUGIN_DIR/$f" ] || die "Missing $PLUGIN_DIR/$f — build the plugin first."
    cp "$PLUGIN_DIR/$f" "$dest/$f"
  done
  ok "Plugin installed: $dest"

  echo
  say "Next steps in Obsidian:"
  echo "  1. Settings -> Community plugins -> enable 'E2EE Vault Sync'"
  echo "  2. Settings -> E2EE Vault Sync:"
  echo "       Server URL    : http://127.0.0.1:${PORT:-8080}   (or https://your-domain)"
  echo "       API token     : $( [ -n "${TOKEN:-}" ] && print_token_masked "$TOKEN" || printf 'see %s' "$RUN_ENV" )"
  echo "       E2EE password : choose one — THE SAME on every device"
  echo "  3. Press 'Test connection', then run 'Force full sync'."
  echo "  Note: on iOS/Android use the LAN/VPS URL — 127.0.0.1 only works on this machine."
}

# ---------------------------------------------------------------- main
case "${1:-}" in
  -h|--help) usage; exit 0 ;;
  "")        : ;;
  *)         echo "Unknown option: $1" >&2; usage; exit 1 ;;
esac

say "Obsidian E2EE Sync — setup wizard"
echo "  1) Run the sync server"
echo "  2) Install the plugin into a vault"
echo "  3) Both (default)"
echo "  4) Stop the background server"
echo "  q) Quit"
prompt "Choose" "3"
case "$REPLY" in
  1) server_flow ;;
  2) plugin_flow ;;
  3) plugin_flow; server_flow ;;
  4) stop_flow ;;
  q|Q) exit 0 ;;
  *)   die "Unknown choice: $REPLY" ;;
esac
